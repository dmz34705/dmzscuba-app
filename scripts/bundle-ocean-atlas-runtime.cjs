// Hermes does not preserve function source for Function#toString. Generate the
// WebView source as a string at build time, never stringify native functions.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../src/features/oceanAtlas');
const raw = ['model.js', 'rendering.js', 'atlasRuntime.js'].map(name => fs.readFileSync(path.join(root, name), 'utf8').replace(/^export /gm, '')).join('\n');

// Minify the inline WebView runtime (the whole document must stay under 2 MB). Top-level names are kept
// because document.js calls atlasRuntime(DATA, { temperatureAt, regionAt, … }) by name.
async function minify(code) {
  let terser;
  try { terser = require('terser'); } catch { console.warn('terser not found; bundling the runtime unminified.'); return code; }
  const result = await terser.minify(code, { ecma: 2020, module: false, toplevel: false, compress: { passes: 2 }, mangle: { toplevel: false }, format: { comments: false } });
  return result.code;
}

(async () => {
  const source = await minify(raw);
  // The hash of the unminified sources lets the atlas test detect a forgotten rebundle.
  const sourceHash = crypto.createHash('sha1').update(raw).digest('hex');
  fs.writeFileSync(path.join(root, 'data/runtimeSource.js'), `// Generated by scripts/bundle-ocean-atlas-runtime.cjs from model.js, rendering.js and atlasRuntime.js. Do not edit.\nexport const runtimeSourceHash = '${sourceHash}';\nexport const runtimeSource = ${JSON.stringify(source)};\n`);
  console.log(`Bundled Ocean Atlas browser runtime for Hermes (${(raw.length / 1024).toFixed(0)} KB → ${(source.length / 1024).toFixed(0)} KB).`);
})().catch(error => { console.error(error); process.exit(1); });
const tiler = fs.readFileSync(path.resolve(root, '../../../node_modules/geojson-vt/geojson-vt.js'), 'utf8');
fs.writeFileSync(path.join(root, 'data/vectorTiler.js'), `// geojson-vt 4.0.2, ISC licence. Generated by bundle-ocean-atlas-runtime.cjs.\nexport const vectorTilerJs = ${JSON.stringify(tiler)};\n`);
fs.copyFileSync(path.resolve(root, '../../../node_modules/geojson-vt/LICENSE'), path.join(root, 'data/GEOJSON-VT-LICENSE.txt'));
